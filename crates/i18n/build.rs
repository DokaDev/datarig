//! Checks the locale catalogs and generates the typed message API (`Label`, `Msg`) into
//! `OUT_DIR/messages.rs`, which `src/lib.rs` includes. A locale is a directory of area files
//! (`locales/<code>/<area>.toml`), merged into one catalog. A catalog problem (missing, extra or
//! mistyped key, placeholder mismatch, a key in two files or in another file than in English)
//! fails the build with the file, the key and the problem. The rules live in `build/catalog.rs`.
//!
//! Also writes `OUT_DIR/files.rs`, the catalog files as text for the tests of other crates
//! (feature `test-util`).

#[path = "build/catalog.rs"]
mod catalog;

use catalog::Policy;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Locales compiled into the binary, the source catalog first. Each needs a `Lang` variant of
/// the same name (`ko` -> `Lang::Ko`). To ship a partial translation, mark it
/// `Policy::Optional`: its missing keys then fall back to English with a build warning.
const LOCALES: &[(&str, Policy)] = &[("en", Policy::Source), ("ko", Policy::Required)];

/// The area files of one locale directory: (area, path), sorted by area.
fn area_files(dir: &Path) -> Result<Vec<(String, PathBuf)>, String> {
    let entries = std::fs::read_dir(dir).map_err(|e| format!("cannot read {}: {e}", dir.display()))?;
    let mut files = Vec::new();
    for e in entries {
        let path = e.map_err(|e| format!("cannot read {}: {e}", dir.display()))?.path();
        if path.extension().is_some_and(|x| x == "toml")
            && let Some(stem) = path.file_stem().and_then(|s| s.to_str())
        {
            files.push((stem.to_string(), path.clone()));
        }
    }
    files.sort();
    Ok(files)
}

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("set by cargo")).join("locales");
    println!("cargo::rerun-if-changed=build/catalog.rs");
    let mut locales = Vec::new();
    let mut errors = Vec::new();
    let mut listing = String::new();
    for &(code, policy) in LOCALES {
        let dir = root.join(code);
        // A directory as a whole: a file added or removed reruns the build script.
        println!("cargo::rerun-if-changed={}", dir.display());
        let label = format!("locales/{code}");
        let paths = match area_files(&dir) {
            Ok(p) => p,
            Err(e) => {
                errors.push(format!("{label}: {e}"));
                continue;
            }
        };
        let mut files = Vec::new();
        for (area, path) in paths {
            println!("cargo::rerun-if-changed={}", path.display());
            match std::fs::read_to_string(&path) {
                Ok(src) => files.push((area.clone(), src)),
                Err(e) => errors.push(format!("{label}/{area}.toml: cannot read {}: {e}", path.display())),
            }
            let _ = writeln!(listing, "    ({code:?}, {area:?}, include_str!({:?})),", path.display().to_string());
        }
        match catalog::merge(code, &label, policy, &files) {
            Ok(loc) => locales.push(loc),
            Err(ps) => errors.extend(ps.iter().map(ToString::to_string)),
        }
    }
    if errors.is_empty() {
        let (errs, warnings) = catalog::check(&locales);
        for w in &warnings {
            println!("cargo::warning={w} (falls back to English)");
        }
        errors.extend(errs.iter().map(ToString::to_string));
    }
    if !errors.is_empty() {
        // Each `cargo::error` fails the build and is printed as `error: datarig-i18n@…: <problem>`.
        for e in &errors {
            println!("cargo::error={e}");
        }
        return;
    }
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("set by cargo"));
    std::fs::write(out.join("messages.rs"), catalog::generate(&locales)).expect("write OUT_DIR/messages.rs");
    let files = format!(
        "// @generated by crates/i18n/build.rs. Do not edit.\n\n\
         /// Every catalog file: (locale code, area, text), by locale and area.\n\
         pub const FILES: &[(&str, &str, &str)] = &[\n{listing}];\n"
    );
    std::fs::write(out.join("files.rs"), files).expect("write OUT_DIR/files.rs");
}
