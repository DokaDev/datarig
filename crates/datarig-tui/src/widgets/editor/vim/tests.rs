/// A count is typed before an operator, after it, or both (they multiply); `0` is a motion
/// unless a count is being typed, and a count too large for the text stops at its end.
#[test]
fn counts() {
    let text = "l1\nl2\nl3\nl4\nl5\nl6\nl7\nl8\nl9\nl10\nl11\nl12";
    let mut e = Editor::new(text);
    typ(&mut e, "10G");
    assert_eq!(e.row, 9);
    typ(&mut e, "gg2d3d");
    assert_eq!(e.lines.len(), 6, "2d3d = 6 lines");
    typ(&mut e, "u10j");
    assert_eq!(e.row, 10);
    typ(&mut e, "999999999k");
    assert_eq!(e.row, 0, "a huge count stops at the first line");
    typ(&mut e, "$10x");
    assert_eq!(e.lines[0], "l", "x from the last grapheme");
    typ(&mut e, "u0");
    assert_eq!(e.col, 0);
    typ(&mut e, "j$");
    typ(&mut e, "10");
    typ(&mut e, "G");
    assert_eq!(e.row, 9, "0 after a digit is part of the count");
}

