fn unfinished_commands_are_cancelled() {
    let text = "one two three";
    let mut e = Editor::new(text);
    for keys in ["d<Esc>", "dz", "3<Esc>", "g<Esc>", "gz", "dgz", "c<Esc>", "y<C-x>"] {
        typ(&mut e, keys);
        assert_eq!((e.text().as_str(), e.mode, e.awaiting_key()), (text, Mode::Normal, false), "{keys}");
    }
    typ(&mut e, "dw");
    assert_eq!(e.text(), "two three", "no count left over");
}

/// `p` puts nothing when the register is empty, and refuses copies that would be too big.
#[test]
fn put_needs_a_register_and_a_sane_size() {
    let mut e = Editor::new("abc");
    typ(&mut e, "p");
    assert_eq!(e.text(), "abc");
    let big = "x".repeat(1 << 20);
    let mut e = at(&big, (0, 0));
    typ(&mut e, "y$99999p");
    assert_eq!(e.len_bytes(), 1 << 20, "100 GB are not put");
}
